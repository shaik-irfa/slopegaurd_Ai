import { useState } from "react";
import { createFileRoute } from "@tanstack/react-router";
import { useMutation, useQuery, useQueryClient } from "@tanstack/react-query";
import { BellRing, Loader2, PlayCircle } from "lucide-react";
import { AppNav } from "@/components/layout/AppNav";
import { AlertCard } from "@/components/decision/AlertCard";
import { alertsQuery, updateAlertStatus } from "@/services/decisionApi";
import type { AlertStatus } from "@/lib/decision/types";

export const Route = createFileRoute("/alerts/")({
  head: () => ({
    meta: [
      { title: "Alert & Response Dashboard — SLOPEGUARD AI" },
      {
        name: "description",
        content:
          "Prototype alert dashboard for the Meghalaya landslide decision-support workflow: demonstration alerts, acknowledgement and resolution history.",
      },
      { property: "og:title", content: "Alert & Response Dashboard — SLOPEGUARD AI" },
      {
        property: "og:description",
        content:
          "Demonstration alerts generated by the SLOPEGUARD AI prototype risk engine, with recommended prototype responses.",
      },
      { property: "og:type", content: "website" },
      { name: "twitter:card", content: "summary_large_image" },
    ],
  }),
  component: AlertsPage,
});

const FILTERS: (AlertStatus | "all")[] = ["all", "active", "acknowledged", "resolved"];

function AlertsPage() {
  const [filter, setFilter] = useState<AlertStatus | "all">("all");
  const queryClient = useQueryClient();
  const alerts = useQuery(alertsQuery(filter));
  const all = useQuery(alertsQuery("all"));

  const status = useMutation({
    mutationFn: ({ id, action }: { id: string; action: "acknowledge" | "resolve" }) =>
      updateAlertStatus(id, action),
    onSuccess: () => void queryClient.invalidateQueries({ queryKey: ["alerts"] }),
  });

  const demo = useMutation({
    mutationFn: async () => {
      const res = await fetch("/api/demo/run", {
        method: "POST",
        headers: { "content-type": "application/json" },
        body: JSON.stringify({}),
      });
      if (!res.ok) throw new Error(`Demonstration run failed (${res.status})`);
      return res.json();
    },
    onSuccess: () => void queryClient.invalidateQueries({ queryKey: ["alerts"] }),
  });

  const list = all.data ?? [];
  const counts = {
    total: list.length,
    active: list.filter((a) => a.status === "active").length,
    acknowledged: list.filter((a) => a.status === "acknowledged").length,
    resolved: list.filter((a) => a.status === "resolved").length,
    critical: list.filter((a) => a.risk_level === "CRITICAL").length,
  };

  return (
    <div className="min-h-[100dvh] bg-background">
      <header className="border-b border-panel-border bg-panel/95 px-4 py-3 backdrop-blur md:px-6">
        <div className="mx-auto flex max-w-5xl flex-col gap-2 md:flex-row md:items-center">
          <div>
            <h1 className="flex items-center gap-2 text-lg font-bold uppercase tracking-wide">
              <BellRing className="size-5 text-hazard" aria-hidden /> Alerts &amp; response
            </h1>
            <p className="text-xs text-muted-foreground">
              Demonstration alerts only — nothing is sent to any authority or phone.
            </p>
          </div>
          <AppNav className="md:ml-auto" />
        </div>
      </header>

      <main className="mx-auto max-w-5xl space-y-5 px-4 py-5 md:px-6">
        <section aria-label="Alert counts" className="grid grid-cols-2 gap-2 sm:grid-cols-5">
          {[
            { label: "Total", value: counts.total },
            { label: "Active", value: counts.active },
            { label: "Acknowledged", value: counts.acknowledged },
            { label: "Resolved", value: counts.resolved },
            { label: "Critical", value: counts.critical },
          ].map(({ label, value }) => (
            <div key={label} className="rounded-lg border border-panel-border bg-panel p-3">
              <p className="text-2xl font-bold leading-none">{all.isLoading ? "—" : value}</p>
              <p className="mt-1 text-[0.7rem] uppercase tracking-wide text-muted-foreground">
                {label}
              </p>
            </div>
          ))}
        </section>

        <div className="flex flex-wrap items-center gap-2">
          <div className="flex gap-1" role="group" aria-label="Filter alerts by status">
            {FILTERS.map((f) => (
              <button
                key={f}
                type="button"
                onClick={() => setFilter(f)}
                aria-pressed={filter === f}
                className={`min-h-10 rounded-md px-3 text-xs font-semibold capitalize ${
                  filter === f ? "bg-primary text-primary-foreground" : "bg-secondary text-muted-foreground"
                }`}
              >
                {f}
              </button>
            ))}
          </div>
          <button
            type="button"
            onClick={() => demo.mutate()}
            disabled={demo.isPending}
            className="ml-auto inline-flex min-h-10 items-center gap-1.5 rounded-md border border-panel-border px-3 text-xs font-semibold transition-colors hover:bg-secondary disabled:opacity-60"
          >
            {demo.isPending ? (
              <Loader2 className="size-3.5 animate-spin" aria-hidden />
            ) : (
              <PlayCircle className="size-3.5" aria-hidden />
            )}
            Run demo scenario (Shillong, 200 mm)
          </button>
        </div>

        {demo.isError ? (
          <p className="text-xs text-hazard">{(demo.error as Error).message}</p>
        ) : null}

        {alerts.isLoading ? (
          <p className="flex items-center gap-2 text-sm text-muted-foreground">
            <Loader2 className="size-4 animate-spin" aria-hidden /> Loading alerts…
          </p>
        ) : alerts.isError ? (
          <p className="text-sm text-hazard">
            Alerts could not be loaded right now. Nothing is substituted.
          </p>
        ) : (alerts.data ?? []).length === 0 ? (
          <p className="text-sm text-muted-foreground">
            No alerts in this view. Assess a HIGH or CRITICAL location on the map, or run the demo
            scenario above.
          </p>
        ) : (
          <ul className="space-y-3">
            {(alerts.data ?? []).map((a) => (
              <li key={a.id}>
                <AlertCard
                  alert={a}
                  busy={status.isPending}
                  onAcknowledge={(id) => status.mutate({ id, action: "acknowledge" })}
                  onResolve={(id) => status.mutate({ id, action: "resolve" })}
                />
              </li>
            ))}
          </ul>
        )}
      </main>
    </div>
  );
}
